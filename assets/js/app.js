            if (!catalogId) catalogId = PUBLIC_BOOKS.find(entry => legacyTitle.includes(entry.catalogId))?.catalogId || '';
            if (!catalogId) catalogId = Object.keys(PRESET_TOCS).find(key => legacyTitle.includes(key)) || '';
