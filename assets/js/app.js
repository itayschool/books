    function applyAccentColor(color) {
        if (!/^#[0-9a-f]{6}$/i.test(color)) return;
        const rgb = color.slice(1).match(/.{2}/g).map(part => parseInt(part, 16));
        const hover = `#${rgb.map(value => Math.round(value * .84).toString(16).padStart(2, '0')).join('')}`;
        document.documentElement.style.setProperty('--primary', color);
        document.documentElement.style.setProperty('--primary-hover', hover);
        document.documentElement.style.setProperty('--primary-soft', `color-mix(in srgb, ${color} 13%, var(--surface-container))`);
        document.documentElement.style.setProperty('--focus', `0 0 0 3px color-mix(in srgb, ${color} 24%, transparent)`);
    }
