    function updateStorageIndicator() {
        const label = document.getElementById('storage-usage');
        if (!label) return;
        const describe = books => {
            const totalBytes = books.reduce((sum, book) => sum + (book.data?.byteLength || book.data?.length || 0) + (book.html ? new Blob([book.html]).size : 0), 0);
            const deletedCount = books.filter(book => book.deletedAt).length;
            return `אחסון הספרייה: ${formatBytes(totalBytes)}${deletedCount ? ` · ${deletedCount} בפריטים שנמחקו` : ''}`;
        };
        label.textContent = describe(libraryBooks);
        if (db) getAllBooksFromDB().then(books => { label.textContent = describe(books); }).catch(() => {});
        if (navigator.storage?.estimate) navigator.storage.estimate().then(estimate => {
            if (estimate.quota) label.title = `מכסת הדפדפן: ${formatBytes(estimate.quota)}`;
        }).catch(() => {});
    }
