        function requestResult(request) {
            return new Promise((resolve, reject) => {
                request.onsuccess = () => resolve(request.result);
                request.onerror = () => reject(request.error || new Error('פעולת מסד הנתונים נכשלה.'));
            });
        }

        function initDB() {
            return new Promise((resolve, reject) => {
                if (!('indexedDB' in window)) {
                    reject(new Error('הדפדפן אינו תומך בשמירת ספרייה מקומית.'));
                    return;
                }
                const request = indexedDB.open(DB_NAME, DB_VERSION);
                request.onupgradeneeded = (event) => {
                    const database = event.target.result;
                    if (!database.objectStoreNames.contains('books')) {
                        database.createObjectStore('books', { keyPath: 'id', autoIncrement: true });
                    }
                    if (!database.objectStoreNames.contains('assets')) {
                        database.createObjectStore('assets', { keyPath: 'id' });
                    }
                };
                request.onsuccess = (event) => {
                    db = event.target.result;
                    db.onversionchange = () => db.close();
                    window.dispatchEvent(new Event('books-db-ready'));
                    resolve(db);
                };
                request.onerror = () => reject(request.error || new Error('לא ניתן לפתוח את הספרייה.'));
                request.onblocked = () => reject(new Error('סגרו לשוניות אחרות של הספרייה ונסו שוב.'));
            });
        }

        function transactionDone(transaction) {
            return new Promise((resolve, reject) => {
                transaction.oncomplete = () => resolve();
                transaction.onerror = () => reject(transaction.error || new Error('שמירת הנתונים נכשלה.'));
                transaction.onabort = () => reject(transaction.error || new Error('שמירת הנתונים בוטלה.'));
            });
        }

        async function saveBookToDB(title, pdfArrayBuffer, thumbnailDataUrl, source = {}) {
            const transaction = db.transaction(['books'], 'readwrite');
            const done = transactionDone(transaction);
            transaction.objectStore('books').add({
                title,
                displayName: '',
                catalogId: source.catalogId || null,
                data: pdfArrayBuffer || null,
                contentType: source.contentType || 'pdf',
                html: source.html || '',
                thumb: thumbnailDataUrl,
                addedAt: new Date().toLocaleDateString('he-IL'),
                addedAtMs: Date.now(),
                sourceName: source.sourceName || `${title}.pdf`,
                sourceLocation: source.sourceLocation || 'local-file',
                progressPage: 1,
                favorite: false,
                folder: '',
                tags: [],
                bookmarks: [],
                toc: []
            });
            await done;
        }

