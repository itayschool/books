        function sanitizeWordHtml(source) {
            const parsed = new DOMParser().parseFromString(`<div>${source || ''}</div>`, 'text/html');
            const root = parsed.body.firstElementChild;
            const allowed = new Set(['P','H1','H2','H3','H4','BLOCKQUOTE','UL','OL','LI','STRONG','B','EM','I','U','S','DEL','SUP','SUB','BR','HR','TABLE','THEAD','TBODY','TFOOT','TR','TH','TD','A','IMG','DIV','SPAN']);
            const blocked = new Set(['SCRIPT','STYLE','IFRAME','OBJECT','EMBED','FORM','INPUT','BUTTON','SVG','VIDEO','AUDIO']);
            const cleanNode = node => {
                [...node.childNodes].forEach(child => {
                    if (child.nodeType !== Node.ELEMENT_NODE) return;
                    if (blocked.has(child.tagName)) { child.remove(); return; }
                    if (!allowed.has(child.tagName)) { cleanNode(child); child.replaceWith(...child.childNodes); return; }
                    const tag = child.tagName;
                    const href = tag === 'A' ? child.getAttribute('href') : '';
                    const src = tag === 'IMG' ? child.getAttribute('src') : '';
                    const alt = tag === 'IMG' ? child.getAttribute('alt') : '';
                    const span = ['TD','TH'].includes(tag) ? child.getAttribute('colspan') : '';
                    const row = ['TD','TH'].includes(tag) ? child.getAttribute('rowspan') : '';
                    [...child.attributes].forEach(attribute => child.removeAttribute(attribute.name));
                    if (tag === 'A' && href) { try { const url = new URL(href, location.href); if (['https:','http:','mailto:'].includes(url.protocol)) { child.setAttribute('href', url.href); child.setAttribute('target', '_blank'); child.setAttribute('rel', 'noopener noreferrer'); } } catch {} }
                    if (tag === 'IMG' && src && /^data:image\/(png|jpeg|gif|webp);base64,/i.test(src)) { child.setAttribute('src', src); child.setAttribute('alt', alt || ''); child.setAttribute('loading', 'lazy'); }
                    if (['TD','TH'].includes(tag)) {
                        if (/^\d{1,2}$/.test(span || '')) child.setAttribute('colspan', span);
                        if (/^\d{1,2}$/.test(row || '')) child.setAttribute('rowspan', row);
                    }
                    cleanNode(child);
                });
            };
            cleanNode(root);
            return root.innerHTML;
        }

