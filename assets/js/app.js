    function tokenizeCalculator(source) {
        const text = String(source).replace(/[×]/g, '*').replace(/[÷]/g, '/').replace(/[−–]/g, '-').replace(/[π]/g, 'pi').replace(/[√]/g, 'sqrt');
        const tokens = [];
        let index = 0;
        while (index < text.length) {
            const rest = text.slice(index);
            if (/^\s/.test(rest)) { index++; continue; }
            const number = rest.match(/^(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?/);
            if (number) { tokens.push({ type: 'number', value: Number(number[0]) }); index += number[0].length; continue; }
            const name = rest.match(/^[A-Za-z]+/);
            if (name) { tokens.push({ type: 'name', value: name[0].toLowerCase() }); index += name[0].length; continue; }
            const symbol = text[index];
            if ('+-*/^!%(),'.includes(symbol)) { tokens.push({ type: 'symbol', value: symbol }); index++; continue; }
            throw new Error(`תו לא מוכר: ${symbol}`);
        }
        if (tokens.length > 600) throw new Error('הביטוי ארוך מדי.');
        return tokens;
    }
    function evaluateCalculator(source) {
        const tokens = tokenizeCalculator(source);
        if (!tokens.length) throw new Error('הקלידו ביטוי כדי לחשב.');
        let cursor = 0;
        const peek = value => tokens[cursor]?.value === value;
        const take = value => { if (!peek(value)) return false; cursor++; return true; };
        const expect = value => { if (!take(value)) throw new Error(`חסר הסימן ${value}`); };
        const angleIn = value => calculatorAngleMode === 'deg' ? value * Math.PI / 180 : value;
        const angleOut = value => calculatorAngleMode === 'deg' ? value * 180 / Math.PI : value;
        const factorial = value => {
            if (!Number.isInteger(value) || value < 0 || value > 170) throw new Error('עצרת זמינה למספרים שלמים בין 0 ל־170.');
            let result = 1; for (let number = 2; number <= value; number++) result *= number; return result;
        };
        const functions = {
            sin: value => Math.sin(angleIn(value)), cos: value => Math.cos(angleIn(value)), tan: value => Math.tan(angleIn(value)),
            asin: value => angleOut(Math.asin(value)), acos: value => angleOut(Math.acos(value)), atan: value => angleOut(Math.atan(value)),
            sinh: value => Math.sinh(value), cosh: value => Math.cosh(value), tanh: value => Math.tanh(value),
            sqrt: value => Math.sqrt(value), cbrt: value => Math.cbrt(value), ln: value => Math.log(value),
            log: value => Math.log10(value), log10: value => Math.log10(value), abs: value => Math.abs(value),
            exp: value => Math.exp(value), floor: value => Math.floor(value), ceil: value => Math.ceil(value),
            round: (value, digits = 0) => { const scale = 10 ** digits; return Math.round(value * scale) / scale; },
            min: (...values) => Math.min(...values), max: (...values) => Math.max(...values), fact: factorial
        };
        function parsePrimary() {
            const token = tokens[cursor];
            if (!token) throw new Error('הביטוי לא הושלם.');
            if (token.type === 'number') { cursor++; return token.value; }
            if (take('(')) { const value = parseAdd(); expect(')'); return value; }
            if (token.type === 'name') {
                cursor++;
                if (token.value === 'pi') return Math.PI;
                if (token.value === 'e') return Math.E;
                if (token.value === 'ans') return calculatorAnswer;
                if (!Object.prototype.hasOwnProperty.call(functions, token.value)) throw new Error(`פונקציה לא מוכרת: ${token.value}`);
                expect('(');
                const args = [];
                if (!peek(')')) {
                    args.push(parseAdd());
                    while (take(',')) args.push(parseAdd());
                }
                expect(')');
                const result = functions[token.value](...args);
                if (Number.isNaN(result)) throw new Error('הפעולה אינה מוגדרת למספרים האלה.');
                return result;
            }
            throw new Error('בדקו את הביטוי והסוגריים.');
        }
        function parsePostfix() {
            let value = parsePrimary();
            while (peek('!') || peek('%')) value = take('!') ? factorial(value) : (take('%'), value / 100);
            return value;
        }
        function parsePower() { const base = parsePostfix(); return take('^') ? base ** parseUnary() : base; }
        function parseUnary() { if (take('+')) return parseUnary(); if (take('-')) return -parseUnary(); return parsePower(); }
        function parseMultiply() {
            let value = parseUnary();
            while (peek('*') || peek('/')) {
                if (take('*')) value *= parseUnary();
                else { take('/'); const divisor = parseUnary(); if (divisor === 0) throw new Error('אי אפשר לחלק באפס.'); value /= divisor; }
            }
            return value;
        }
        function parseAdd() {
            let value = parseMultiply();
            while (peek('+') || peek('-')) value = take('+') ? value + parseMultiply() : (take('-'), value - parseMultiply());
            return value;
        }
        const result = parseAdd();
        if (cursor !== tokens.length) throw new Error(`תו לא צפוי: ${tokens[cursor].value}`);
        if (!Number.isFinite(result)) throw new Error('התוצאה אינה מספר סופי.');
        return result;
    }
