    function sanitizeSvg(text) {
        const parsed = new DOMParser().parseFromString(text, 'image/svg+xml'); const svg = parsed.documentElement;
        if (svg.localName !== 'svg' || parsed.querySelector('parsererror')) throw new Error('הקובץ אינו SVG תקין.');
        svg.querySelectorAll('script,style,foreignObject,iframe,object,embed').forEach(node => node.remove());
        [svg, ...svg.querySelectorAll('*')].forEach(node => [...node.attributes].forEach(attribute => {
            if (/^on/i.test(attribute.name) || attribute.name === 'style' || /javascript:/i.test(attribute.value) || (/url\s*\(/i.test(attribute.value) && !/url\s*\(\s*["']?#/i.test(attribute.value)) || ((attribute.name === 'href' || attribute.name.endsWith(':href')) && !attribute.value.startsWith('#'))) node.removeAttribute(attribute.name);
        }));
        return new XMLSerializer().serializeToString(svg);
    }
